'use strict';
const assert = require('node:assert/strict');
const { adaptLegacyToolCall: adapt } = require('../out/legacy-bridge.js');
function call(name,args,id=1){return {jsonrpc:'2.0',id,method:'tools/call',params:{name,arguments:args}};}
const x=adapt(call('execute_shell_command_code',{command:'echo Test',cwd:'@shell:main-Fallout-aabbccdd'}));
assert.equal(x.kind,'rewrite');
assert.equal(x.request.params.arguments.shell_id,'main-Fallout-aabbccdd');
assert.equal(x.request.params.arguments.command,'echo Test');
assert.ok(!('cwd' in x.request.params.arguments));
assert.equal(adapt(call('execute_shell_command_code',{command:'pwd'})).kind,'error');
assert.equal(adapt(call('execute_shell_command_code',{command:'windows',cwd:'@mcp'})).kind,'control');
assert.equal(adapt(call('execute_shell_command_code',{command:'shells',cwd:'@mcp'})).command,'shells');
assert.equal(adapt(call('execute_shell_command_code',{command:'bad',cwd:'@mcp'})).kind,'error');
assert.equal(adapt(call('execute_shell_command_code',{command:'pwd',shell_id:'abc'})).kind,'pass');
const y=adapt(call('list_files_code',{path:'@shell:my_shell/src',recursive:true}));
assert.equal(y.kind,'rewrite');
assert.equal(y.request.params.arguments.shell_id,'my_shell');
assert.equal(y.request.params.arguments.path,'src');
const z=adapt(call('copy_file_code',{sourcePath:'@shell:my_shell/src/a.txt',targetPath:'@shell:my_shell/dst/b.txt'}));
assert.equal(z.kind,'rewrite');
assert.equal(z.request.params.arguments.targetPath,'dst/b.txt');
assert.equal(adapt(call('copy_file_code',{sourcePath:'@shell:one/path',targetPath:'@shell:two/path'})).kind,'error');
assert.equal(adapt(call('read_file_code',{path:'README.md'})).kind,'error');
assert.equal(adapt({method:'tools/list',id:1}).kind,'pass');
const native=adapt(call('search_symbols_code',{query:'@shell:2 FooClass'}));
assert.equal(native.kind,'rewrite');
assert.equal(native.request.params.arguments.shell_id,'2');
assert.equal(native.request.params.arguments.query,'FooClass');
assert.equal(adapt(call('search_symbols_code',{query:'FooClass'})).kind,'error');
console.log('PASS: legacy calls require shell selectors; cross-shell paths denied; admin commands read-only');